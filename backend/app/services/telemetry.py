"""Software-only telemetry simulator for demonstrating the conceptual IoT flow.

Every value produced here is synthetic and is stored with ``source="simulated"``.
The generator uses a simple diurnal sine pattern plus noise; it does not model any
real farm or sensor."""

from __future__ import annotations

import math
import random
from datetime import datetime, timedelta, timezone

from app.models import EnvironmentalObservation, ObservationSource


def generate(
    farm_id: int,
    hours: int,
    interval_minutes: int,
    include_excursion: bool,
    seed: int | None,
    recorded_by_id: int | None,
    now: datetime | None = None,
) -> list[EnvironmentalObservation]:
    rng = random.Random(seed)
    now = (now or datetime.now(timezone.utc)).replace(second=0, microsecond=0)
    steps = max(1, (hours * 60) // interval_minutes)
    start = now - timedelta(minutes=interval_minutes * (steps - 1))
    excursion_at = rng.randrange(steps) if include_excursion else None

    out: list[EnvironmentalObservation] = []
    for i in range(steps):
        t = start + timedelta(minutes=interval_minutes * i)
        phase = 2 * math.pi * ((t.hour + t.minute / 60) - 9) / 24  # peak mid-afternoon
        temp = 26 + 4 * math.sin(phase) + rng.gauss(0, 0.6)
        rh = 62 - 10 * math.sin(phase) + rng.gauss(0, 2.5)
        nh3 = max(0.0, 9 + rng.gauss(0, 2.0))
        if excursion_at is not None and abs(i - excursion_at) <= 1:
            # Always exceed the provisional limits, whatever the time of day.
            temp = max(temp + 8, 33.5 + rng.random())
            nh3 = max(nh3 + 22, 27.0 + rng.random())
        out.append(
            EnvironmentalObservation(
                farm_id=farm_id,
                observed_at=t,
                shed_label="Simulated shed",
                temperature_c=round(temp, 1),
                relative_humidity_pct=round(min(100.0, max(0.0, rh)), 1),
                ammonia_ppm=round(nh3, 1),
                source=ObservationSource.SIMULATED,
                notes="Synthetic value generated by the telemetry simulator; not a measurement.",
                recorded_by_id=recorded_by_id,
            )
        )
    return out
